"""The Western-only preset tier: every model US or EU, one twin per base preset.

Generated by scripts/gen_western_presets.py into
src/reasoner/domain/preset_registry_western.py. The rest of the preset suite
(bloc diversity, temperatures, validate_presets) already runs over these.
"""
import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(ROOT / "src"))

from reasoner.core.model_policy import WESTERN_BLOCS, WESTERN_TAG  # noqa: E402
from reasoner.domain.preset_core import (  # noqa: E402
    build_auto_preset,
    get_preset_price_tier,
    is_western_preset,
    western_variant,
)
from reasoner.domain.preset_registry import _REGISTRY as PRESETS  # noqa: E402
from reasoner.infrastructure.llm.registry import bloc_of  # noqa: E402

_WESTERN = sorted(p for p in PRESETS if WESTERN_TAG in PRESETS[p].get("tags", []))
_BASE = sorted(p for p in PRESETS if p not in _WESTERN)


def _models(preset: dict) -> list[str]:
    out = [preset["primary_id"], *preset.get("routing", {}).values()]
    out += preset.get("fallback_routing", {}).values()
    for chain in preset.get("cascading_routing", {}).values():
        out += chain
    return out


@pytest.mark.unit
def test_every_base_preset_has_a_western_twin():
    assert _WESTERN and len(_WESTERN) == len(_BASE)
    assert sorted(western_variant(p) for p in _BASE) == _WESTERN


@pytest.mark.unit
def test_tag_and_id_agree():
    """run_blocs() keys off the id; the UI and API key off the tag."""
    for pid, preset in PRESETS.items():
        assert is_western_preset(pid) == (WESTERN_TAG in preset.get("tags", [])), pid


@pytest.mark.unit
@pytest.mark.parametrize("preset_id", _WESTERN)
def test_every_model_is_us_or_eu(preset_id):
    bad = [m for m in _models(PRESETS[preset_id]) if bloc_of(m) not in WESTERN_BLOCS]
    assert not bad, f"{preset_id}: non-Western models {bad}"


@pytest.mark.unit
@pytest.mark.parametrize("preset_id", _WESTERN)
def test_twin_keeps_method_and_tier(preset_id):
    base_id = preset_id.replace("-western-", "-")
    assert PRESETS[preset_id]["method"] == PRESETS[base_id]["method"]
    assert get_preset_price_tier(preset_id) == get_preset_price_tier(base_id)


@pytest.mark.unit
def test_auto_preset_picks_the_western_twin():
    assert build_auto_preset("debate", "premium", western=True) == "debate-western-premium"
    assert build_auto_preset("no-such-method", western=True) == "multi-perspective-western-budget"
    assert western_variant("auto-budget") == "auto-western-budget"
    assert western_variant("auto") == "auto-western-budget"


@pytest.mark.unit
def test_generated_file_is_current():
    result = subprocess.run(
        [sys.executable, str(ROOT / "scripts" / "gen_western_presets.py"), "--check"],
        capture_output=True, text=True, cwd=ROOT,
    )
    assert result.returncode == 0, result.stdout + result.stderr
