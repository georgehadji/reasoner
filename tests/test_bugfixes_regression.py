# ──────────────────────────────────────────────────────────────────────────────
# BUG-016: Cache load failure permanently disables disk cache
# ──────────────────────────────────────────────────────────────────────────────

class TestTokenCacheLoadFailure:
    """Verify that a failed disk load does NOT permanently disable the cache."""

    @pytest.mark.asyncio
    async def test_load_failure_allows_retry(self, tmp_path, monkeypatch):
        """If _load_from_disk fails, _loaded should remain False so the next call retries."""
        from reasoner.token_cache import TokenAwareCache

        cache = TokenAwareCache(cache_dir=tmp_path)
        load_attempts = 0

        async def failing_load():
            nonlocal load_attempts
            load_attempts += 1
            raise OSError("Simulated disk I/O error")

        monkeypatch.setattr(cache, "_load_from_disk", failing_load)

        # The failure is swallowed — a corrupt cache file must not fail the request —
        # but the cache must not be marked loaded, or it never re-reads from disk.
        await cache._ensure_loaded()

        assert cache._loaded is False, "_loaded must remain False after failed load"
        assert load_attempts == 1

        # Second call should ALSO attempt load (retry behavior)
        await cache._ensure_loaded()

        assert load_attempts == 2, "Second call should retry load, not skip it"

        # Retries are capped so a permanently unreadable cache stops retrying.
        for _ in range(5):
            await cache._ensure_loaded()
        assert load_attempts == cache._MAX_LOAD_ATTEMPTS

    @pytest.mark.asyncio
    async def test_successful_load_sets_loaded_true(self, tmp_path):
        """A successful load should set _loaded = True."""
        from reasoner.token_cache import TokenAwareCache

        cache = TokenAwareCache(cache_dir=tmp_path)
        await cache._ensure_loaded()
        assert cache._loaded is True

    @pytest.mark.asyncio
    async def test_corrupted_file_then_recovery(self, tmp_path, monkeypatch):
        """A corrupted cache file should not permanently disable the cache."""
        from reasoner.token_cache import TokenAwareCache

        # Create a corrupted JSON file
        bad_file = tmp_path / "bad.json"
        bad_file.write_text("NOT JSON")

        cache = TokenAwareCache(cache_dir=tmp_path)

        # First load should handle the corrupted file gracefully
        await cache._ensure_loaded()
        assert cache._loaded is True

        # The corrupted file should have been removed
        assert not bad_file.exists()


