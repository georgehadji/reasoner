# BUG-014: Race condition in PostgresQuotaRepository._get_pool()
# ──────────────────────────────────────────────────────────────────────────────

class TestQuotaRepoPoolRaceCondition:
    """Verify that concurrent calls to _get_pool() create only ONE asyncpg pool."""

    @pytest.mark.asyncio
    async def test_concurrent_get_pool_creates_single_pool(self, monkeypatch):
        """Multiple concurrent _get_pool() calls must result in exactly one create_pool."""
        from reasoner.infrastructure.persistence.quota_repo_postgres import PostgresQuotaRepository

        call_count = 0

        async def mock_create_pool(*args, **kwargs):
            nonlocal call_count
            call_count += 1
            # Simulate async work to widen the race window
            await asyncio.sleep(0.01)
            return MagicMock()

        monkeypatch.setattr("asyncpg.create_pool", mock_create_pool)

        repo = PostgresQuotaRepository("postgresql://test", pool_size=2)

        # Fire 10 concurrent _get_pool() calls
        await asyncio.gather(*[repo._get_pool() for _ in range(10)])

        assert call_count == 1, f"Expected 1 pool creation, got {call_count}"

    @pytest.mark.asyncio
    async def test_sequential_get_pool_reuses_pool(self, monkeypatch):
        """Sequential calls must reuse the existing pool."""
        from reasoner.infrastructure.persistence.quota_repo_postgres import PostgresQuotaRepository

        call_count = 0

        async def mock_create_pool(*args, **kwargs):
            nonlocal call_count
            call_count += 1
            return MagicMock()

        monkeypatch.setattr("asyncpg.create_pool", mock_create_pool)
        # _pool is a class attribute; an earlier test may have left one behind.
        monkeypatch.setattr(PostgresQuotaRepository, "_pool", None)

        repo = PostgresQuotaRepository("postgresql://test", pool_size=2)

        await repo._get_pool()
        await repo._get_pool()
        await repo._get_pool()

        assert call_count == 1


