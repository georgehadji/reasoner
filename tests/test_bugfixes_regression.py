# BUG-005: CSRF token generation/verification secret mismatch
# ──────────────────────────────────────────────────────────────────────────────

class TestCsrfSecretConsistency:
    """Verify that generate_csrf_token and verify_csrf_token use the SAME secret."""

    @pytest.fixture(autouse=True)
    def _ensure_csrf_secret(self, monkeypatch):
        """Ensure CSRF_SECRET is set for all tests in this class.

        The settings object is built once at import, so setting the env var alone
        does not change settings.CSRF_SECRET — patch the attribute the module reads.
        """
        from reasoner.core.settings import settings

        monkeypatch.setenv("CSRF_SECRET", "test-csrf-secret-do-not-reuse")
        monkeypatch.setattr(settings, "CSRF_SECRET", "test-csrf-secret-do-not-reuse")

    def test_generate_and_verify_use_same_secret(self, monkeypatch):
        """A token generated by generate_csrf_token must be verifiable by verify_csrf_token."""
        # Force re-import with the new env var
        import importlib
        from reasoner.api import csrf as csrf_module

        importlib.reload(csrf_module)

        token = csrf_module.generate_csrf_token()
        signed = csrf_module.sign_csrf_token(token)
        assert csrf_module.verify_csrf_token(signed) is True

    def test_signed_token_roundtrip(self, monkeypatch):
        """generate_signed_csrf_token → verify_csrf_token must succeed."""
        import importlib
        from reasoner.api import csrf as csrf_module

        importlib.reload(csrf_module)

        signed = csrf_module.generate_signed_csrf_token()
        assert csrf_module.verify_csrf_token(signed) is True

    def test_tampered_token_fails(self, monkeypatch):
        """Tampering with the token should cause verification to fail."""
        import importlib
        from reasoner.api import csrf as csrf_module

        importlib.reload(csrf_module)

        signed = csrf_module.generate_signed_csrf_token()
        tampered = signed[:-4] + "XXXX"
        assert csrf_module.verify_csrf_token(tampered) is False

    def test_expired_token_fails(self, monkeypatch):
        """A token with a past expiry should fail verification."""
        import importlib
        from reasoner.api import csrf as csrf_module

        importlib.reload(csrf_module)

        # Manually create an expired token
        expiry = int(time.time()) - 10  # 10 seconds ago
        nonce = secrets.token_urlsafe(16)
        payload = f"{expiry}:{nonce}"
        sig = hmac.new(
            csrf_module._CSRF_SECRET, payload.encode(), hashlib.sha256
        ).hexdigest()[:16]
        expired_token = f"{payload}:{sig}"
        signed = csrf_module.sign_csrf_token(expired_token)
        assert csrf_module.verify_csrf_token(signed) is False


