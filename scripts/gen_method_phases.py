#!/usr/bin/env python3
"""Generate the run card's phase plan per method from the backend flows.

Writes ``ui-next/src/lib/method-phases.generated.ts``: for every method in
``WorkflowFactory``, the ``(id, name)`` of each step its flow's
``get_phases`` returns. The run card (components/chat/RunProgress) reads it to
say "step N of M" and what comes next. The plans used to be written by hand
and drifted from the flows. ``tests/unit/test_method_phases_generated.py``
fails when the checked-in file differs from what this script would write.

Plans come from a default ``PipelineState``. A flow that drops a step at run
time (Multi-Perspective skips Evidence Search and Stress Testing for a simple
problem) still lists it here; the card drops a planned step once a later one
runs.

Usage:
  python scripts/gen_method_phases.py          # write the file
  python scripts/gen_method_phases.py --check  # exit 1 if it would change
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from reasoner.application.flows.factory import WorkflowFactory  # noqa: E402
from reasoner.domain.pipeline_state import PipelineState  # noqa: E402

OUT = ROOT / "ui-next" / "src" / "lib" / "method-phases.generated.ts"


def _num(x: float) -> str:
    return str(int(x)) if float(x).is_integer() else repr(float(x))


def render() -> str:
    # The factory's map is the one place that says which flow runs a method.
    strategies = WorkflowFactory()._strategies
    lines = [
        "// GENERATED by scripts/gen_method_phases.py from each flow's get_phases.",
        "// Do not edit: run `python scripts/gen_method_phases.py`.",
        "import type { MethodPhase } from './types';",
        "",
        "export const METHOD_PHASES: Record<string, MethodPhase[]> = {",
    ]
    for method in sorted(strategies):
        steps = strategies[method]().get_phases(PipelineState())
        lines.append(f"  {json.dumps(method.replace('_', '-'))}: [")
        lines += [f"    {{ id: {_num(s.num)}, name: {json.dumps(s.name)} }}," for s in steps]
        lines.append("  ],")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is stale: run scripts/gen_method_phases.py")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
